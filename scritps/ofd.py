import random

v = list(range(20))
random.shuffle(v)

print('0: [', end='')

for i in range(100):
    val = v[i%20]
    if (i+1)%5 == 0:
        print(f'{val}],')
        print(f'{(i+1)//5}: [', end='')
    else:
        print(f'{val}, ', end='')
        
    if (i+1) % 20 == 0:
        random.shuffle(v)

